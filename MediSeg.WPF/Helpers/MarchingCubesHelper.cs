    /// <summary>
    /// 레이블맵 byte[W*H*D]에서 Marching Cubes를 실행해 WPF MeshGeometry3D를 반환합니다.
    /// </summary>
    public static class MarchingCubesHelper
    {
        // 각 장기 레이블 인덱스(1~8)에 대해 별도 Mesh를 생성
        public static Dictionary<byte, MeshGeometry3D> ExtractMeshes(
            byte[] labelmap, int w, int h, int d,
            double spacingX, double spacingY, double spacingZ,
            byte[]? targetLabels = null)
        {
            targetLabels ??= Enumerable.Range(1, 8).Select(i => (byte)i).ToArray();
            var result = new Dictionary<byte, MeshGeometry3D>();

            foreach (var label in targetLabels)
            {
                bool hasAny = false;
                for (int i = 0; i < labelmap.Length; i++)
                    if (labelmap[i] == label) { hasAny = true; break; }
                if (!hasAny) continue;

                var mesh = RunMarchingCubes(labelmap, w, h, d, spacingX, spacingY, spacingZ, label);
                if (mesh.Positions.Count > 0) result[label] = mesh;
            }
            return result;
        }

        private static MeshGeometry3D RunMarchingCubes(
            byte[] lm, int w, int h, int d,
            double sx, double sy, double sz, byte label)
        {
            var positions  = new Point3DCollection();
            var normals    = new Vector3DCollection();
            var indices    = new Int32Collection();
            int vertCount  = 0;

            for (int z = 0; z < d - 1; z++)
            for (int y = 0; y < h - 1; y++)
            for (int x = 0; x < w - 1; x++)
            {
                // 8 corners
                float[] vals = new float[8];
                vals[0] = SampleLabel(lm, x,   y,   z,   w, h, d, label);
                vals[1] = SampleLabel(lm, x+1, y,   z,   w, h, d, label);
                vals[2] = SampleLabel(lm, x+1, y+1, z,   w, h, d, label);
                vals[3] = SampleLabel(lm, x,   y+1, z,   w, h, d, label);
                vals[4] = SampleLabel(lm, x,   y,   z+1, w, h, d, label);
                vals[5] = SampleLabel(lm, x+1, y,   z+1, w, h, d, label);
                vals[6] = SampleLabel(lm, x+1, y+1, z+1, w, h, d, label);
                vals[7] = SampleLabel(lm, x,   y+1, z+1, w, h, d, label);

                int cubeIndex = 0;
                for (int i = 0; i < 8; i++)
                    if (vals[i] > 0.5f) cubeIndex |= (1 << i);

                if (cubeIndex == 0 || cubeIndex == 255) continue;

                var tris = MarchingCubesTables.TriTable[cubeIndex];
                for (int t = 0; t < tris.Length; t += 3)
                {
                    if (tris[t] < 0) break;

                    var p0 = Interpolate(x, y, z, sx, sy, sz, tris[t],   vals);
                    var p1 = Interpolate(x, y, z, sx, sy, sz, tris[t+1], vals);
                    var p2 = Interpolate(x, y, z, sx, sy, sz, tris[t+2], vals);

                    var normal = Vector3D.CrossProduct(p1 - p0, p2 - p0);
                    normal.Normalize();

                    positions.Add(p0); normals.Add(normal);
                    positions.Add(p1); normals.Add(normal);
                    positions.Add(p2); normals.Add(normal);

                    indices.Add(vertCount);
                    indices.Add(vertCount + 1);
                    indices.Add(vertCount + 2);
                    vertCount += 3;
                }
            }

            return new MeshGeometry3D
            {
                Positions       = positions,
                Normals         = normals,
                TriangleIndices = indices
            };
        }

        private static float SampleLabel(byte[] lm, int x, int y, int z, int w, int h, int d, byte label)
        {
            if (x < 0 || y < 0 || z < 0 || x >= w || y >= h || z >= d) return 0f;
            return lm[z * w * h + y * w + x] == label ? 1f : 0f;
        }

        private static Point3D Interpolate(int cx, int cy, int cz, double sx, double sy, double sz,
            int edge, float[] vals)
        {
            var (a, b) = MarchingCubesTables.EdgeVertices[edge];
            var pa = MarchingCubesTables.CornerOffsets[a];
            var pb = MarchingCubesTables.CornerOffsets[b];
            float va = vals[a], vb = vals[b];
            float t = (va + vb == 0) ? 0.5f : (0.5f - va) / (vb - va);
            t = Math.Clamp(t, 0f, 1f);
            return new Point3D(
                (cx + pa.x + t * (pb.x - pa.x)) * sx,
                (cy + pa.y + t * (pb.y - pa.y)) * sy,
                (cz + pa.z + t * (pb.z - pa.z)) * sz);
        }
    }

